import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync('games/smart-coins/stories.js','utf8');
const state={jobHistory:[{job:'Художник',day:1}],storyDone:[],stars:0,coins:0};
const env={state,cityPlace:8,selectedJob:-1,jobAttempt:false,render(){},save(){},tone(){},speak(){},document:{getElementById(){return {innerHTML:''}}}};
vm.createContext(env);vm.runInContext(source,env);
env.openStory(0);
assert.equal(env.storyReady(0),false,'Old work should not satisfy a newly opened story');
env.chooseStory(0);env.goStoryWork();
assert.equal(state.activeStory,0,'Return journey remembers active story');
state.jobHistory.push({job:'Художник',day:2});
assert.equal(env.storyReady(0),true,'Fresh work satisfies story');
env.finishStory();
assert.equal(state.stars,1,'Story grants one star');
assert.equal(state.storyDone.length,1,'Story records completion');
assert.equal(state.activeStory,null,'Completed story clears active marker');
env.finishStory();assert.equal(state.stars,1,'Story cannot reward twice');
env.openStory(1);assert.equal(env.storyReady(1),false);
console.log('Story continuity tests passed.');
